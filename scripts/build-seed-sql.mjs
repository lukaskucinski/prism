#!/usr/bin/env node
/**
 * Build a Postgres INSERT script for prism_layers from the APPEIT catalog.
 * Mirrors the Python loader in modal/prism/seed/load_layers.py so we can
 * seed the table without needing the conda env up.
 *
 * Usage:
 *   node scripts/build-seed-sql.mjs > /tmp/prism_layers_seed.sql
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const CATALOG_PATH = path.join(REPO_ROOT, "modal/prism/config/layers_config.json");

const GROUP_TO_CATEGORY = {
  "Critical Habitats": "critical_habitat",
  "Floodplains": "floodplain_wetland",
  "Historic Places": "historic",
  "Federal/Tribal Land": "tribal_federal_land",
  "EPA Programs": "epa_program",
  "Infrastructure": "infrastructure",
  "State Lands": "state_protected",
  "Environmental Justice": "environmental_justice",
};
const TIER = {
  critical_habitat: "high",
  floodplain_wetland: "high",
  historic: "medium",
  tribal_federal_land: "medium",
  epa_program: "medium",
  infrastructure: "low",
  state_protected: "low",
  environmental_justice: "medium",
};
const WEIGHT = { high: 30, medium: 15, low: 5 };

function quote(v) {
  if (v == null) return "NULL";
  return `'${String(v).replace(/'/g, "''")}'`;
}

function main() {
  const catalog = JSON.parse(fs.readFileSync(CATALOG_PATH, "utf8"));
  const rows = [];
  const groupCounts = {};
  const skipped = [];
  for (const e of catalog) {
    groupCounts[e.group] = (groupCounts[e.group] || 0) + 1;
    if (!e.name || !e.url) {
      skipped.push({ n: e.name, why: "missing fields" });
      continue;
    }
    const gt = (e.geometry_type || "").toLowerCase();
    if (!["polygon", "point", "line"].includes(gt)) {
      skipped.push({ n: e.name, why: `geometry_type:${gt}` });
      continue;
    }
    const category = GROUP_TO_CATEGORY[e.group] || "state_protected";
    // Walk the URL path backward to find the service-name segment immediately
    // before the FeatureServer/MapServer suffix. Handles nested paths like
    // services/TIGERweb/AIANNHA/MapServer.
    const parts = e.url.split("/").filter(Boolean);
    const idx = parts.findIndex(
      (p) => p === "FeatureServer" || p === "MapServer"
    );
    const serviceName = idx > 0 ? parts[idx - 1] : "unknown";
    const serviceType = idx >= 0 ? parts[idx] : "FeatureServer";
    const serviceSlug = serviceName.replace(/[^A-Za-z0-9_]+/g, "_").replace(/^_+|_+$/g, "");
    // Name-slug PK: stable across re-runs, unique per catalog entry, human-readable
    const nameSlug = e.name
      .replace(/[^A-Za-z0-9]+/g, "_")
      .replace(/^_+|_+$/g, "")
      .toLowerCase()
      .slice(0, 60);
    const layerId = `${nameSlug}__${serviceSlug}-${e.layer_id ?? 0}`;
    rows.push({
      layer_id: layerId,
      layer_name: e.name,
      raw_group: e.group || null,
      friction_category: category,
      source_url: e.url,
      source_layer_id: e.layer_id ?? 0,
      service_type: serviceType,
      geometry_type: gt,
      friction_weight: WEIGHT[TIER[category]],
      friction_tier: TIER[category],
      description: e.description || null,
    });
  }
  // Dedup by layer_id (collisions can happen if two catalog entries hit the
  // same service+sublayer; later wins)
  const dedup = new Map();
  for (const r of rows) dedup.set(r.layer_id, r);

  process.stderr.write(
    `Parsed ${rows.length} rows (${dedup.size} unique by layer_id); skipped ${skipped.length}\n`
  );
  process.stderr.write(`Group counts: ${JSON.stringify(groupCounts)}\n`);

  console.log(`-- Generated by scripts/build-seed-sql.mjs from layers_config.json`);
  console.log(`-- ${dedup.size} rows; ${skipped.length} skipped`);
  console.log(``);
  const cols = [
    "layer_id",
    "layer_name",
    "raw_group",
    "friction_category",
    "source_url",
    "source_layer_id",
    "service_type",
    "geometry_type",
    "friction_weight",
    "friction_tier",
    "description",
  ];
  const BATCH = 50;
  const all = [...dedup.values()];
  for (let i = 0; i < all.length; i += BATCH) {
    const chunk = all.slice(i, i + BATCH);
    console.log(`INSERT INTO prism_layers (${cols.join(", ")}) VALUES`);
    const tuples = chunk.map((r) => {
      const vals = cols.map((c) =>
        typeof r[c] === "number" ? String(r[c]) : quote(r[c])
      );
      return `  (${vals.join(", ")})`;
    });
    console.log(tuples.join(",\n"));
    console.log(
      `ON CONFLICT (layer_id) DO UPDATE SET
       layer_name = EXCLUDED.layer_name,
       raw_group = EXCLUDED.raw_group,
       friction_category = EXCLUDED.friction_category,
       source_url = EXCLUDED.source_url,
       source_layer_id = EXCLUDED.source_layer_id,
       service_type = EXCLUDED.service_type,
       geometry_type = EXCLUDED.geometry_type,
       friction_weight = EXCLUDED.friction_weight,
       friction_tier = EXCLUDED.friction_tier,
       description = EXCLUDED.description,
       updated_at = now();`
    );
    console.log(``);
  }
}

main();
